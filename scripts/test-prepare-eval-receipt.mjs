import assert from 'node:assert/strict';
import crypto from 'node:crypto';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { buildPacket } from './build-eval-packet.mjs';
import { prepareReceipt } from './prepare-eval-receipt.mjs';
import { preflightReceipt } from './eval-feedback-loop.mjs';

const source = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const root = fs.mkdtempSync(path.join(os.tmpdir(), 'prepare-eval-'));
const hash = file => crypto.createHash('sha256').update(fs.readFileSync(file)).digest('hex');
try {
  fs.mkdirSync(path.join(root, 'scripts'));
  for (const name of ['prepare-eval-receipt.mjs', 'eval-feedback-loop.mjs', 'eval-attempt-evidence.mjs', 'eval-config-planner.mjs', 'eval-grade-binding.mjs', 'bounded-files.mjs', 'build-eval-packet.mjs']) fs.copyFileSync(path.join(source, 'scripts', name), path.join(root, 'scripts', name));
  fs.mkdirSync(path.join(root, 'node_modules/@mehul0810'), { recursive: true });
  fs.symlinkSync(path.join(source, 'node_modules/@mehul0810/agent-harness'), path.join(root, 'node_modules/@mehul0810/agent-harness'), 'dir');
  fs.mkdirSync(path.join(root, 'skill-evals'));
  const baseline = path.join(root, 'skill-evals/behavior-baselines.json');
  fs.writeFileSync(baseline, JSON.stringify({ schemaVersion: 2, baselines: [{ name: 'sample', requiredChecks: ['a', 'b'] }] }));
  const original = hash(baseline);
  const revision = 'a'.repeat(40);
  const input = path.join(root, 'input');
  fs.mkdirSync(input);
  fs.writeFileSync(path.join(input, 'input.json'), JSON.stringify({ id: 'packet', request: 'Test', artifacts: [] }));
  const packet = path.join(root, 'packet');
  buildPacket(input, packet, revision);
  const manifestSha256 = hash(path.join(packet, 'manifest.json'));
  const result = path.join(root, 'result.json');
  fs.writeFileSync(result, JSON.stringify({ cases: [{ packetId: 'packet', id: 'case', outcome: 'raw output' }] }));
  const gradePath = path.join(root, 'grade.json');
  const decisions = ['a', 'b'].map((check, i) => ({ check, packetId: 'packet', caseId: 'case', result: i ? 'incomplete' : 'fail', resultSha256: hash(result), manifestSha256 }));
  const grade = { schemaVersion: 1, scorerIdentity: 'scorer', decisions };
  fs.writeFileSync(gradePath, JSON.stringify(grade));
  const actor = identity => ({ identity, exposedPaths: ['evidence'], expectedAnswersExposed: false, candidateSourceExposed: false });
  const descriptor = { schemaVersion: 1, baseline: 'sample', testedRevision: revision, evaluation: { evaluator: actor('performer'), scorer: actor('scorer') }, gradePath, checks: ['a', 'b'].map(name => ({ name, cases: [{ packetId: 'packet', caseId: 'case', packetPath: packet, manifestSha256, resultPath: result }] })) };
  const descriptorPath = path.join(root, 'descriptor.json');
  fs.writeFileSync(descriptorPath, JSON.stringify(descriptor));
  let hashes = 0;
  prepareReceipt(root, descriptor, { hashBytes: bytes => { hashes++; return crypto.createHash('sha256').update(bytes).digest('hex'); } });
  assert.equal(hashes, 3, 'generation hashes the shared manifest, result, and grade once each');
  const run = () => spawnSync(process.execPath, [fs.realpathSync(path.join(root, 'scripts/prepare-eval-receipt.mjs')), '--descriptor', descriptorPath], { encoding: 'utf8' });
  let execution = run();
  assert.equal(execution.status, 0, execution.stderr);
  let receipt = JSON.parse(execution.stdout);
  const compact = { ...descriptor, groups: [{ alias: 'shared', packetId: 'packet', packetPath: packet, manifestSha256, resultPath: result }], checks: descriptor.checks.map(check => ({ name: check.name, cases: [{ group: 'shared', caseId: 'case' }] })) };
  fs.writeFileSync(descriptorPath, JSON.stringify(compact));
  const compactRun = run();
  assert.equal(compactRun.status, 0, compactRun.stderr);
  assert.deepEqual(JSON.parse(compactRun.stdout), receipt);
  assert.match(compactRun.stderr, /preflight: failed; admission: not-performed/);
  hashes = 0;
  prepareReceipt(root, compact, { hashBytes: bytes => { hashes++; return crypto.createHash('sha256').update(bytes).digest('hex'); } });
  assert.equal(hashes, 3, 'compact references reuse evidence digests');
  const bad = (change, pattern) => { const value = structuredClone(compact); change(value); assert.throws(() => prepareReceipt(root, value), pattern); };
  bad(d => { d.groups.push({ ...d.groups[0] }); }, /duplicate/);
  bad(d => { delete d.groups[0].alias; }, /missing, duplicate, or unsafe/);
  bad(d => { d.groups[0].alias = '../unsafe'; }, /unsafe/);
  bad(d => { d.checks[0].cases[0].group = 'unknown'; }, /unknown or missing/);
  bad(d => { delete d.checks[0].cases[0].group; }, /unknown or missing/);
  bad(d => { delete d.checks[0].cases[0].caseId; }, /caseId/);
  bad(d => { delete d.groups[0].resultPath; }, /evidence fields/);
  bad(d => { d.checks[0].cases[0].packetId = 'packet'; }, /group case/);
  bad(d => { d.groups.push({ ...d.groups[0], alias: 'unused' }); }, /unused/);
  assert.throws(() => prepareReceipt(root, { ...descriptor, checks: compact.checks }), /invalid case fields/);
  fs.writeFileSync(descriptorPath, JSON.stringify(descriptor));
  assert.deepEqual(receipt.checks.map(x => x.result), ['fail', 'incomplete']);
  assert.match(execution.stderr, /preflight: failed; admission: not-performed/);
  const receiptPath = path.join(root, 'receipt.json');
  fs.writeFileSync(receiptPath, execution.stdout, { flag: 'wx' });
  let verification = spawnSync(process.execPath, [fs.realpathSync(path.join(root, 'scripts/eval-feedback-loop.mjs')), 'preflight', '--receipt', receiptPath], { encoding: 'utf8' });
  assert.equal(JSON.parse(verification.stdout).state, 'failed');
  const preflightCli = (file, ...flags) => spawnSync(process.execPath, [fs.realpathSync(path.join(root, 'scripts/eval-feedback-loop.mjs')), 'preflight', '--receipt', file, ...flags], { encoding: 'utf8' });
  let strict = preflightCli(receiptPath, '--require-grade');
  assert.equal(strict.status, 0);
  assert.equal(JSON.parse(strict.stdout).state, 'failed');
  assert.equal(JSON.parse(strict.stdout).admission, 'not-performed');
  const legacy = structuredClone(receipt); delete legacy.preparation;
  const legacyPath = path.join(root, 'legacy.json'); fs.writeFileSync(legacyPath, JSON.stringify(legacy));
  assert.equal(JSON.parse(preflightCli(legacyPath).stdout).state, 'failed');
  strict = preflightCli(legacyPath, '--require-grade');
  assert.notEqual(strict.status, 0);
  assert.match(JSON.parse(strict.stdout).errors.join(' '), /requires a prepared schemaVersion 1/);
  assert.equal(preflightReceipt(root, legacy, { requireGrade: true }).state, 'invalid');
  const v2Path = path.join(root, 'v2.json'); fs.writeFileSync(v2Path, JSON.stringify({ schemaVersion: 2, status: 'draft' }));
  strict = preflightCli(v2Path, '--require-grade');
  assert.notEqual(strict.status, 0);
  assert.match(JSON.parse(strict.stdout).errors.join(' '), /schemaVersion 2 receipts are unsupported/);
  const invalid = (change, pattern) => {
    const mutated = structuredClone(receipt); change(mutated);
    const checked = preflightReceipt(root, mutated);
    assert.equal(checked.state, 'invalid');
    assert.match(checked.errors.join(' '), pattern);
  };
  invalid(r => { r.checks[0].result = 'pass'; }, /does not match grade/);
  invalid(r => { r.checks[1].result = 'pass'; }, /does not match grade/);
  invalid(r => { r.checks.pop(); }, /unmapped grade/);
  invalid(r => { r.checks[0].cases[0].caseId = 'substituted'; }, /missing, duplicate/);
  invalid(r => { r.checks[0].cases[0].resultSha256 = '0'.repeat(64); }, /unbound or stale/);
  invalid(r => { r.checks[0].cases[0].manifestSha256 = '0'.repeat(64); }, /unbound or stale/);
  invalid(r => { r.evaluation.scorer.identity = 'someone-else'; }, /grade identity/);
  invalid(r => { r.preparation.gradeSha256 = '0'.repeat(64); }, /grade hash mismatch/);
  const extraGrade = { ...grade, decisions: [...grade.decisions, { ...grade.decisions[0], caseId: 'extra' }] };
  fs.writeFileSync(gradePath, JSON.stringify(extraGrade));
  invalid(r => { r.preparation.gradeSha256 = hash(gradePath); }, /unmapped grade/);
  fs.writeFileSync(gradePath, JSON.stringify(grade));
  grade.decisions.push({ ...grade.decisions[0] }); fs.writeFileSync(gradePath, JSON.stringify(grade));
  assert.throws(() => prepareReceipt(root, descriptor), /duplicate/);
  verification = spawnSync(process.execPath, [fs.realpathSync(path.join(root, 'scripts/eval-feedback-loop.mjs')), 'preflight', '--receipt', receiptPath], { encoding: 'utf8' });
  assert.match(JSON.parse(verification.stdout).errors.join(' '), /grade hash mismatch/);
  grade.decisions.pop(); grade.decisions[0].resultSha256 = '0'.repeat(64); fs.writeFileSync(gradePath, JSON.stringify(grade));
  assert.throws(() => prepareReceipt(root, descriptor), /unbound or stale/);
  grade.decisions[0].resultSha256 = hash(result); grade.decisions.pop(); fs.writeFileSync(gradePath, JSON.stringify(grade));
  assert.throws(() => prepareReceipt(root, descriptor), /missing, duplicate/);
  grade.decisions.push(decisions[1] ?? { check: 'b', packetId: 'packet', caseId: 'case', result: 'incomplete', resultSha256: hash(result), manifestSha256 });
  fs.writeFileSync(result, JSON.stringify({ cases: [{ packetId: 'packet', id: 'case', outcome: 'one' }, { packetId: 'packet', id: 'case', outcome: 'two' }] }));
  assert.throws(() => prepareReceipt(root, descriptor), /ambiguous/);
  fs.writeFileSync(result, JSON.stringify({ cases: [{ packetId: 'packet', id: 'case', outcome: 'raw output' }] }));
  decisions[0].result = 'pass'; fs.writeFileSync(gradePath, JSON.stringify(grade));
  execution = run(); assert.equal(execution.status, 0, execution.stderr); assert.match(execution.stderr, /preflight: incomplete/);
  assert.equal(preflightReceipt(root, JSON.parse(execution.stdout)).state, 'incomplete');
  const incompletePath = path.join(root, 'incomplete.json'); fs.writeFileSync(incompletePath, execution.stdout);
  strict = preflightCli(incompletePath, '--require-grade');
  assert.equal(strict.status, 0);
  assert.equal(JSON.parse(strict.stdout).state, 'incomplete');
  assert.equal(JSON.parse(strict.stdout).admission, 'not-performed');
  const largeResult = path.join(root, 'large-result.json');
  const largeGrade = path.join(root, 'large-grade.json');
  const count = 200;
  fs.writeFileSync(largeResult, JSON.stringify({ cases: Array.from({ length: count }, (_, i) => ({ packetId: 'packet', id: `case-${i}`, outcome: 'observed' })) }));
  const refs = Array.from({ length: count }, (_, i) => ({ packetId: 'packet', caseId: `case-${i}`, packetPath: packet, manifestSha256, resultPath: largeResult }));
  fs.writeFileSync(largeGrade, JSON.stringify({ schemaVersion: 1, scorerIdentity: 'scorer', decisions: refs.map(ref => ({ check: 'a', packetId: ref.packetId, caseId: ref.caseId, result: 'fail', resultSha256: hash(largeResult), manifestSha256 })) }));
  const many = { ...descriptor, gradePath: largeGrade, checks: [{ name: 'a', cases: refs }, descriptor.checks[1]] };
  // The baseline's second check also needs a separately bound decision.
  const lg = JSON.parse(fs.readFileSync(largeGrade));
  lg.decisions.push({ ...grade.decisions[1] }); fs.writeFileSync(largeGrade, JSON.stringify(lg));
  assert.equal(prepareReceipt(root, many).preflight.state, 'failed');
  assert.throws(() => prepareReceipt(root, { ...many, checks: [{ name: 'a', cases: Array(513).fill(refs[0]) }] }), /entry limit/);
  const oversizedReceipt = structuredClone(receipt);
  oversizedReceipt.checks[0].cases = Array(513).fill(oversizedReceipt.checks[0].cases[0]);
  assert.equal(preflightReceipt(root, oversizedReceipt).state, 'invalid');
  fs.writeFileSync(result, JSON.stringify({ cases: [{ packetId: 'packet', id: 'case', outcome: 'changed' }] }));
  execution = run(); assert.notEqual(execution.status, 0); assert.equal(execution.stdout, ''); assert.match(execution.stderr, /stale/);
  verification = spawnSync(process.execPath, [fs.realpathSync(path.join(root, 'scripts/eval-feedback-loop.mjs')), 'preflight', '--receipt', receiptPath], { encoding: 'utf8' });
  assert.equal(JSON.parse(verification.stdout).state, 'invalid');
  assert.throws(() => prepareReceipt(root, { ...descriptor, schemaVersion: 2, attempts: [] }), /invalid descriptor fields|Only schemaVersion/);
  assert.equal(hash(baseline), original);
  assert.equal(hash(receiptPath), crypto.createHash('sha256').update(JSON.stringify(receipt, null, 2) + '\n').digest('hex'));
  console.log('Draft receipt preparation tests passed');
} finally { fs.rmSync(root, { recursive: true, force: true }); }
